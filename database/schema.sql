CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(80) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS customers (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 nickname VARCHAR(100) NOT NULL DEFAULT '',
 customer_kind VARCHAR(20) NOT NULL DEFAULT 'person',
 affiliation VARCHAR(100) NOT NULL DEFAULT '',
 contact_name VARCHAR(100) NOT NULL DEFAULT '',
 payer_name VARCHAR(100) NOT NULL DEFAULT '',
 preferred_fulfillment VARCHAR(20) NOT NULL DEFAULT '',
 phone VARCHAR(50) NOT NULL DEFAULT '',
 address VARCHAR(500) NOT NULL DEFAULT '',
 area VARCHAR(100) NOT NULL DEFAULT '',
 notes TEXT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS products (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 code VARCHAR(30) NOT NULL UNIQUE,
 name VARCHAR(100) NOT NULL,
 weight_g INT UNSIGNED NULL,
 price_cents INT UNSIGNED NOT NULL,
 legacy_key VARCHAR(191) NULL UNIQUE,
 sort_order INT UNSIGNED NOT NULL DEFAULT 100000,
 active TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS orders (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 request_key CHAR(32) NOT NULL UNIQUE,
 customer_id INT UNSIGNED NOT NULL,
 customer_name VARCHAR(100) NOT NULL,
 delivery_address VARCHAR(500) NOT NULL,
 order_date DATE NOT NULL,
 delivery_date DATE NULL,
 fulfillment VARCHAR(10) NOT NULL,
 subtotal_cents INT UNSIGNED NOT NULL,
 discount_cents INT UNSIGNED NOT NULL DEFAULT 0,
 delivery_fee_cents INT UNSIGNED NOT NULL DEFAULT 0,
 other_sales_cents INT UNSIGNED NOT NULL DEFAULT 0,
 other_charges_cents INT UNSIGNED NOT NULL DEFAULT 0,
 additional_income_cents INT UNSIGNED NOT NULL DEFAULT 0,
 import_batch_id INT UNSIGNED NULL,
 delivery_state_known TINYINT NOT NULL DEFAULT 1,
 payment_state_known TINYINT NOT NULL DEFAULT 1,
 production_state TINYINT NULL,
 total_cents INT UNSIGNED NOT NULL,
 received_cents INT UNSIGNED NOT NULL DEFAULT 0,
 cancelled TINYINT NOT NULL DEFAULT 0,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 shipped_units INT UNSIGNED NOT NULL DEFAULT 0,
 delivered TINYINT NOT NULL DEFAULT 0,
 paid TINYINT NOT NULL DEFAULT 0,
 payment_method VARCHAR(20) DEFAULT NULL,
 notes TEXT NOT NULL,
 created_by INT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (customer_id) REFERENCES customers(id),
 FOREIGN KEY (created_by) REFERENCES users(id),
 INDEX (delivery_date), INDEX (order_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS order_items (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id INT UNSIGNED NOT NULL,
 product_id INT UNSIGNED NOT NULL,
 product_code VARCHAR(30) NOT NULL,
 product_name VARCHAR(100) NOT NULL,
 weight_g INT UNSIGNED NULL,
 unit_price_cents INT UNSIGNED NOT NULL,
 quantity INT UNSIGNED NOT NULL,
 delivered_quantity INT UNSIGNED NOT NULL DEFAULT 0,
 cancelled_quantity INT UNSIGNED NOT NULL DEFAULT 0,
 unit_discount_cents INT UNSIGNED NOT NULL DEFAULT 0,
 extra_discount_units INT UNSIGNED NOT NULL DEFAULT 0,
 FOREIGN KEY (order_id) REFERENCES orders(id),
 FOREIGN KEY (product_id) REFERENCES products(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS login_attempts (
 identity_hash CHAR(64) PRIMARY KEY,
 attempts INT NOT NULL DEFAULT 0,
 last_attempt DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS payments (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id INT UNSIGNED NOT NULL,
 request_key CHAR(32) NOT NULL UNIQUE,
 amount_cents INT UNSIGNED NOT NULL,
 additional_income_cents INT UNSIGNED NOT NULL DEFAULT 0,
 payer_name VARCHAR(100) NOT NULL DEFAULT '',
 method VARCHAR(20) NOT NULL,
 paid_on DATE NULL,
 note VARCHAR(500) NOT NULL DEFAULT '',
 created_by INT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE,
 FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS payment_allocations (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 payment_id INT UNSIGNED NOT NULL,
 item_id INT UNSIGNED NULL,
 allocation_type VARCHAR(30) NOT NULL DEFAULT 'product',
 amount_cents INT UNSIGNED NOT NULL,
 FOREIGN KEY (payment_id) REFERENCES payments(id) ON DELETE CASCADE,
 FOREIGN KEY (item_id) REFERENCES order_items(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS order_events (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id INT UNSIGNED NOT NULL,
 request_key CHAR(32) NOT NULL UNIQUE,
 kind VARCHAR(30) NOT NULL,
 summary VARCHAR(500) NOT NULL,
 detail JSON NOT NULL,
 created_by INT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE,
 FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS import_sources (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 source_sha CHAR(64) NOT NULL UNIQUE,
 filename VARCHAR(255) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS import_batches (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 source_id INT UNSIGNED NOT NULL,
 plan_sha CHAR(64) NOT NULL,
 backup_name VARCHAR(255) NOT NULL,
 backup_sha CHAR(64) NOT NULL,
 summary JSON NOT NULL,
 created_by INT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE (source_id,plan_sha),
 FOREIGN KEY (source_id) REFERENCES import_sources(id),
 FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS import_records (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 source_id INT UNSIGNED NOT NULL,
 entity_type VARCHAR(20) NOT NULL,
 source_ref VARCHAR(100) NOT NULL,
 content_sha CHAR(64) NOT NULL,
 state VARCHAR(20) NOT NULL,
 target_id INT UNSIGNED NULL,
 source_snapshot JSON NOT NULL,
 last_batch_id INT UNSIGNED NOT NULL,
 UNIQUE (source_id,entity_type,source_ref),
 FOREIGN KEY (source_id) REFERENCES import_sources(id),
 FOREIGN KEY (last_batch_id) REFERENCES import_batches(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS import_batch_rows (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 batch_id INT UNSIGNED NOT NULL,
 entity_type VARCHAR(20) NOT NULL,
 source_ref VARCHAR(100) NOT NULL,
 state VARCHAR(20) NOT NULL,
 operation VARCHAR(20) NOT NULL,
 content_sha CHAR(64) NOT NULL,
 target_id INT UNSIGNED NULL,
 source_snapshot JSON NOT NULL,
 UNIQUE (batch_id,entity_type,source_ref),
 FOREIGN KEY (batch_id) REFERENCES import_batches(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
